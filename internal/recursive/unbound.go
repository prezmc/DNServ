// Package recursive runs the bundled Unbound as a child process and
// resolves through it. DNSSEC validation and iterative resolution from the
// root servers are where bugs become security holes, so DNServe relies on
// Unbound's long-proven implementation for them; the Go node generates its
// configuration, supervises it and fronts it with the filter and cache.
package recursive

import (
	"bufio"
	"context"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"net"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"sync/atomic"
	"text/template"
	"time"

	"github.com/miekg/dns"
)

// Options configure the Unbound instance.
type Options struct {
	Binary  string
	Dir     string // working directory for config and trust anchor
	Port    int
	Threads int
	CacheMB int
	// ServeExpired lets Unbound answer from expired records while it
	// refreshes them (its own serve-stale).
	ServeExpired time.Duration
	// OutgoingInterface optionally pins outbound queries to one local
	// address (tunnel mode).
	OutgoingInterface string
}

// healthName is answered locally by Unbound, so readiness can be checked
// without network access.
const healthName = "ready.dnserve.health."

// TrustAnchorSources are where distributions ship the DNSSEC root key.
var TrustAnchorSources = []string{
	"/usr/share/dnssec-root/trusted-key.key", // Alpine (dnssec-root)
	"/usr/share/dns/root.key",                // Debian/Ubuntu (dns-root-data)
	"/etc/unbound/root.key",
	"/var/lib/unbound/root.key",
}

