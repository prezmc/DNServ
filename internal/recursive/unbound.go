// Config renders unbound.conf for o.
func Config(o Options) (string, error) {
	threads := max(o.Threads, 1)
	cache := max(o.CacheMB, 16)
	data := struct {
		Options
		Threads, MsgMB, RRsetMB int
		ServeExpired            int
	}{
		Options: o, Threads: threads,
		MsgMB: cache / 3, RRsetMB: cache - cache/3,
		ServeExpired: int(o.ServeExpired / time.Second),
	}
	var b strings.Builder
	if err := confTmpl.Execute(&b, data); err != nil {
		return "", err
	}
	return b.String(), nil
}

// Unbound supervises the child process.
type Unbound struct {
	opt   Options
	log   *slog.Logger
	ready atomic.Bool
	// restarts counts unexpected exits.
	restarts atomic.Int64
}

// New creates a supervisor. Call Run to start it.
func New(o Options, log *slog.Logger) *Unbound { return &Unbound{opt: o, log: log} }

// Addr is where Unbound listens.
func (u *Unbound) Addr() string { return net.JoinHostPort("127.0.0.1", strconv.Itoa(u.opt.Port)) }

// Ready reports whether Unbound is answering.
func (u *Unbound) Ready() bool { return u.ready.Load() }

// Restarts reports how many times Unbound exited unexpectedly.
func (u *Unbound) Restarts() int64 { return u.restarts.Load() }

// Prepare writes the config and seeds the trust anchor. It is separate
// from Run so a bad setup fails at startup with a clear error.
func (u *Unbound) Prepare() (string, error) {
	if err := os.MkdirAll(u.opt.Dir, 0o700); err != nil {
		return "", err
	}
	bin, err := exec.LookPath(u.opt.Binary)
	if err != nil {
		return "", fmt.Errorf("unbound not found (%s): %w", u.opt.Binary, err)
	}
	if err := seedTrustAnchor(filepath.Join(u.opt.Dir, "root.key")); err != nil {
		return "", err
	}
	conf, err := Config(u.opt)
	if err != nil {
		return "", err
	}
	path := filepath.Join(u.opt.Dir, "unbound.conf")
	if err := os.WriteFile(path, []byte(conf), 0o600); err != nil {
		return "", err
	}
	if chk, err := exec.LookPath(filepath.Join(filepath.Dir(bin), "unbound-checkconf")); err == nil {
		if out, err := exec.Command(chk, path).CombinedOutput(); err != nil {
			return "", fmt.Errorf("unbound config check failed: %s", strings.TrimSpace(string(out)))
		}
	}
	return path, nil
}

func seedTrustAnchor(dst string) error {
	if _, err := os.Stat(dst); err == nil {
		return nil
	}
	for _, src := range TrustAnchorSources {
		b, err := os.ReadFile(src)
		if err != nil {
			continue
		}
		return os.WriteFile(dst, b, 0o600)
	}
	return fmt.Errorf("no DNSSEC root trust anchor found (looked in %s)", strings.Join(TrustAnchorSources, ", "))
}

// Run starts Unbound and restarts it if it exits, with backoff, until ctx
// ends. It returns after the child has stopped.
func (u *Unbound) Run(ctx context.Context, confPath string) {
	backoff := time.Second
	for ctx.Err() == nil {
		started := time.Now()
		err := u.runOnce(ctx, confPath)
		u.ready.Store(false)
		if ctx.Err() != nil {
			return
		}
		u.restarts.Add(1)
		if time.Since(started) > time.Minute {
			backoff = time.Second
		}
		u.log.Error("unbound exited; restarting", "err", err, "in", backoff)
		select {
		case <-ctx.Done():
			return
		case <-time.After(backoff):
		}
		backoff = min(backoff*2, 30*time.Second)
	}
}

func (u *Unbound) runOnce(ctx context.Context, confPath string) error {
	cmd := exec.Command(u.opt.Binary, "-d", "-p", "-c", confPath)
	cmd.Dir = u.opt.Dir
	stderr, err := cmd.StderrPipe()
	if err != nil {
		return err
	}
	cmd.Stdout = cmd.Stderr
	if err := cmd.Start(); err != nil {
		return err
	}
	go u.pipeLogs(stderr)

	done := make(chan error, 1)
	go func() { done <- cmd.Wait() }()

	probeCtx, cancelProbe := context.WithCancel(ctx)
	defer cancelProbe()
	go u.watchReady(probeCtx)

	select {
	case err := <-done:
		if err == nil {
			err = errors.New("exited")
		}
		return err
	case <-ctx.Done():
		_ = cmd.Process.Signal(os.Interrupt)
		select {
		case <-done:
		case <-time.After(5 * time.Second):
			_ = cmd.Process.Kill()
			<-done
		}
		return ctx.Err()
	}
}

func (u *Unbound) pipeLogs(r io.Reader) {
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := sc.Text()
		lvl := slog.LevelInfo
		switch {
		case strings.Contains(line, "error:"), strings.Contains(line, "fatal"):
			lvl = slog.LevelError
		case strings.Contains(line, "warning:"):
			lvl = slog.LevelWarn
		}
		u.log.Log(context.Background(), lvl, "unbound", "line", line)
	}
}

// watchReady polls the local health name until ctx ends.
func (u *Unbound) watchReady(ctx context.Context) {
	t := time.NewTicker(250 * time.Millisecond)
	defer t.Stop()
	slow := false
	for {
		ok := Probe(ctx, u.Addr())
		if ok && !u.ready.Load() {
			u.log.Info("unbound ready", "addr", u.Addr())
		}
		u.ready.Store(ok)
		if ok && !slow {
			t.Reset(5 * time.Second)
			slow = true
		}
		select {
		case <-ctx.Done():
			return
		case <-t.C:
		}
	}
}

// Probe asks Unbound for its local health record.
func Probe(ctx context.Context, addr string) bool {
	m := new(dns.Msg)
	m.SetQuestion(healthName, dns.TypeA)
	c := &dns.Client{Timeout: time.Second}
	r, _, err := c.ExchangeContext(ctx, m, addr)
	return err == nil && r.Rcode == dns.RcodeSuccess && len(r.Answer) == 1
}

// WaitReady blocks until Unbound answers or ctx ends.
func (u *Unbound) WaitReady(ctx context.Context) error {
	for !u.Ready() {
		select {
		case <-ctx.Done():
			return fmt.Errorf("unbound did not become ready: %w", ctx.Err())
		case <-time.After(100 * time.Millisecond):
		}
	}
	return nil
}
